export type TKey = keyof typeof T;

const LangContext = createContext<{
  lang: LangCode;
  cycle: () => void;
  t: (k: TKey) => string;
} | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [i, setI] = useState(0);
  const lang = LANGS[i]!.code;
  const cycle = () => setI((v) => (v + 1) % LANGS.length);
  const t = (k: TKey) => T[k][lang];
  return (
    <LangContext.Provider value={{ lang, cycle, t }}>{children}</LangContext.Provider>
  );
}

export function useLang() {
  const ctx = useContext(LangContext);
  if (!ctx) throw new Error("useLang must be used inside LanguageProvider");
  return ctx;
}

export function langLabel(code: LangCode) {
  return LANGS.find((l) => l.code === code)!.label;
}

